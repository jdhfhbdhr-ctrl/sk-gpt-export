import React from 'react';
import { Image } from '@/components/ui/image';
import { User, Sparkles, FileText } from 'lucide-react';
import MarkdownText from '@/components/MarkdownText';

// Read-only view of a single message — used on the public share page.
// Mirrors the styling of ChatMessage so user/AI bubbles stay visually distinct.
export default function ChatMessageView({ message }) {
  const isUser = message.role === 'user';
  return (
    <div className={`flex gap-3 ${isUser ? 'flex-row-reverse' : 'flex-row'}`}>
      <div className={`mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-full ${isUser ? 'bg-primary text-primary-foreground' : 'bg-muted text-foreground'}`}>
        {isUser ? <User size={16} /> : <Sparkles size={16} />}
      </div>
      <div className="flex min-w-0 max-w-[85%] flex-col gap-1.5">
        <span className="px-1 text-[11px] font-medium text-muted-foreground">{isUser ? 'You' : 'SK GPT'}</span>
        <div className={`max-w-full rounded-2xl px-4 py-3 text-sm leading-relaxed ${isUser ? 'bg-primary text-primary-foreground' : 'bg-muted'}`}>
          {message.content && (isUser
            ? <p className="whitespace-pre-wrap break-words">{message.content}</p>
            : <MarkdownText>{message.content}</MarkdownText>
          )}
          {message.image_url && (
            <div className="mt-2 overflow-hidden rounded-xl">
              <Image src={message.image_url} alt="Generated by SK GPT" className="w-full" fittingType="fill" />
            </div>
          )}
          {message.file_name && (
            <div className="mt-2 flex items-center gap-2 rounded-lg bg-background/50 px-3 py-2 text-xs">
              <FileText size={14} />
              <span className="truncate">{message.file_name}</span>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}