import React, { useEffect, useState } from 'react';
import { Image } from '@/components/ui/image';

export default function ChatImage({ src }) {
  const [dimensions, setDimensions] = useState({ width: 1, height: 1 });
  const [status, setStatus] = useState('loading');
  useEffect(() => {
    let current = true;
    setStatus('loading');
    const probe = new window.Image();
    probe.onload = () => { if (current) { setDimensions({ width: probe.naturalWidth, height: probe.naturalHeight }); setStatus('ready'); } };
    probe.onerror = () => { if (current) setStatus('error'); };
    probe.src = src;
    return () => { current = false; };
  }, [src]);
  if (status === 'error') return <div role="alert" className="mt-3 text-sm text-destructive">The generated image could not be loaded. <a href={src} target="_blank" rel="noopener noreferrer" className="underline">Open original image</a></div>;
  return <div className="mt-3 w-full max-w-xl">
    {status === 'loading' && <p role="status" className="text-sm text-muted-foreground">Loading image…</p>}
    <a href={src} target="_blank" rel="noopener noreferrer" title="Open full-size image" className="block w-full overflow-hidden rounded-xl">
      <Image src={src} alt="Generated by SK GPT" fittingType="fit" originWidth={dimensions.width} originHeight={dimensions.height} className="block w-full" style={{ aspectRatio: `${dimensions.width} / ${dimensions.height}` }} onError={() => setStatus('error')} />
    </a>
  </div>;
}